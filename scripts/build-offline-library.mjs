/** The native fallback and PWA execute the same dependency-free retrieval code. */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import ts from 'typescript'

const compiled = ts.transpileModule(readFileSync('lib/offline-knowledge.ts', 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
}).outputText
const engine = '// Generated by scripts/build-offline-library.mjs. Do not edit.\n(function () { var exports = {};\n' + compiled + '\nglobalThis.EOSKnowledge = exports; })();\n'
// Public static sources also exist in web-only deployments, where /native is excluded.
const outputs = { 'public/knowledge.js': engine }
if (existsSync('native/www')) {
  outputs['native/www/knowledge.js'] = engine
  outputs['native/www/knowledge-ui.js'] = readFileSync('public/knowledge-ui.js', 'utf8')
  outputs['native/www/offline.html'] = readFileSync('public/offline.html', 'utf8')
}

for (const [path, text] of Object.entries(outputs)) {
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== text) throw new Error(`Offline artifact out of date: ${path}`)
  } else writeFileSync(path, text)
}
